"""Evaluate the frozen classifier using independent patient-disjoint labeled images."""
import argparse
import csv
import json
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from lunglens.config import Settings
from lunglens.classifier import Classifier
from lunglens.imaging import decode_input, MAX_BYTES
from lunglens.schemas import EvaluationRequest
from lunglens.evaluation import evaluate_observations


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv',type=Path,help='CSV with image_path, view, and exact finding labels as 0/1; empty labels excluded')
    parser.add_argument('--output',type=Path,default=Path('evaluation.json'))
    args = parser.parse_args()
    classifier = Classifier(Settings.from_env())
    classifier.ready()
    labels = list(classifier.model.pathologies)
    references = dict(zip(labels,map(float,classifier.thresholds)))
    observations, seen_files = [], set()
    with args.csv.open(newline='',encoding='utf-8-sig') as file:
        reader = csv.DictReader(file)
        if not {'image_path','view'}.issubset(reader.fieldnames or []):
            parser.error('CSV requires image_path and view columns')
        for index,row in enumerate(reader):
            if row['view'] not in {'AP','PA'}:
                raise ValueError('Only declared AP/PA views are supported')
            path = Path(row['image_path'])
            if not path.is_absolute():
                path = args.csv.parent / path
            path = path.resolve()
            if path in seen_files:
                raise ValueError('Duplicate image files are not allowed in one evaluation')
            seen_files.add(path)
            if path.stat().st_size > MAX_BYTES:
                raise ValueError('Evaluation image exceeds the 20 MB limit')
            truths = {}
            for label in labels:
                truth = (row.get(label) or '').strip()
                if truth and truth not in {'0','1'}:
                    raise ValueError('Labels must be 0, 1 or blank; map uncertain labels explicitly first')
                if truth:
                    truths[label] = int(truth)
            if not truths:
                continue
            image,metadata = decode_input(path.read_bytes())
            if metadata.get('recorded_view') and metadata['recorded_view'] != row['view']:
                raise ValueError('CSV view conflicts with DICOM view metadata')
            result = classifier.predict(image,row['view'])
            for item in result['findings']:
                if item['label'] in truths:
                    observations.append({'case_id':f'case_{index:06d}','label':item['label'],
                                         'truth':truths[item['label']],'score':item['score']})
    payload = EvaluationRequest(model_weights=classifier.settings.weights,
                                checkpoint_sha256=classifier.sha256,observations=observations)
    report = evaluate_observations(payload,references)
    report['provenance_verified'] = True
    report['provenance_scope'] = 'Scores were generated by this CLI using the recorded local checkpoint; dataset independence and label quality remain unverified'
    report['model'] = classifier.info()
    args.output.write_text(json.dumps(report,indent=2,allow_nan=False),encoding='utf-8')
    print(f'Wrote aggregate metrics to {args.output}')


if __name__ == '__main__':
    main()
